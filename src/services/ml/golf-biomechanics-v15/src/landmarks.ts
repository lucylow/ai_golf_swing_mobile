export const LM={
  NOSE:0,LEFT_SHOULDER:11,RIGHT_SHOULDER:12,LEFT_ELBOW:13,RIGHT_ELBOW:14,LEFT_WRIST:15,RIGHT_WRIST:16,
  LEFT_INDEX:19,RIGHT_INDEX:20,LEFT_THUMB:21,RIGHT_THUMB:22,LEFT_HIP:23,RIGHT_HIP:24,LEFT_KNEE:25,RIGHT_KNEE:26,
  LEFT_ANKLE:27,RIGHT_ANKLE:28,LEFT_HEEL:29,RIGHT_HEEL:30,LEFT_FOOT_INDEX:31,RIGHT_FOOT_INDEX:32
} as const;
export const golfSide=(handedness:'left'|'right')=>handedness==='right'?{lead:'left' as const,trail:'right' as const}:{lead:'right' as const,trail:'left' as const};
export function idx(side:'left'|'right',part:'SHOULDER'|'ELBOW'|'WRIST'|'INDEX'|'THUMB'|'HIP'|'KNEE'|'ANKLE'|'HEEL'|'FOOT_INDEX'):number {
  const left:Record<string,number>={SHOULDER:LM.LEFT_SHOULDER,ELBOW:LM.LEFT_ELBOW,WRIST:LM.LEFT_WRIST,INDEX:LM.LEFT_INDEX,THUMB:LM.LEFT_THUMB,HIP:LM.LEFT_HIP,KNEE:LM.LEFT_KNEE,ANKLE:LM.LEFT_ANKLE,HEEL:LM.LEFT_HEEL,FOOT_INDEX:LM.LEFT_FOOT_INDEX};
  const right:Record<string,number>={SHOULDER:LM.RIGHT_SHOULDER,ELBOW:LM.RIGHT_ELBOW,WRIST:LM.RIGHT_WRIST,INDEX:LM.RIGHT_INDEX,THUMB:LM.RIGHT_THUMB,HIP:LM.RIGHT_HIP,KNEE:LM.RIGHT_KNEE,ANKLE:LM.RIGHT_ANKLE,HEEL:LM.RIGHT_HEEL,FOOT_INDEX:LM.RIGHT_FOOT_INDEX};
  return (side==='left'?left:right)[part];
}
