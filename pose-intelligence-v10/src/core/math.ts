export type Vec2 = { x:number; y:number };
export type Vec3 = { x:number; y:number; z:number };
export type Mat3 = [number,number,number,number,number,number,number,number,number];
export type Mat4 = number[];
export const EPS = 1e-9;
export const clamp=(v:number,a:number,b:number)=>Math.max(a,Math.min(b,v));
export const saturate=(v:number)=>clamp(v,0,1);
export const lerp=(a:number,b:number,t:number)=>a+(b-a)*t;
export const add=(a:Vec3,b:Vec3):Vec3=>({x:a.x+b.x,y:a.y+b.y,z:a.z+b.z});
export const sub=(a:Vec3,b:Vec3):Vec3=>({x:a.x-b.x,y:a.y-b.y,z:a.z-b.z});
export const mul=(a:Vec3,s:number):Vec3=>({x:a.x*s,y:a.y*s,z:a.z*s});
export const dot=(a:Vec3,b:Vec3)=>a.x*b.x+a.y*b.y+a.z*b.z;
export const cross=(a:Vec3,b:Vec3):Vec3=>({x:a.y*b.z-a.z*b.y,y:a.z*b.x-a.x*b.z,z:a.x*b.y-a.y*b.x});
export const norm=(a:Vec3)=>Math.sqrt(dot(a,a));
export const normalize=(a:Vec3):Vec3=>{const n=norm(a);return n<EPS?{x:0,y:0,z:0}:mul(a,1/n)};
export const distance=(a:Vec3,b:Vec3)=>norm(sub(a,b));
export const angleDeg=(a:Vec3,b:Vec3)=>{const na=norm(a),nb=norm(b);if(na<EPS||nb<EPS)return 0;return Math.acos(clamp(dot(a,b)/(na*nb),-1,1))*180/Math.PI};
export const mat3Identity=():Mat3=>[1,0,0,0,1,0,0,0,1];
export const mat3Mul=(A:Mat3,B:Mat3):Mat3=>{
  const o:number[]=[]; for(let r=0;r<3;r++)for(let c=0;c<3;c++)o[r*3+c]=A[r*3]*B[c]+A[r*3+1]*B[3+c]+A[r*3+2]*B[6+c]; return o as Mat3;
};
export const mat3Vec=(A:Mat3,v:Vec3):Vec3=>({x:A[0]*v.x+A[1]*v.y+A[2]*v.z,y:A[3]*v.x+A[4]*v.y+A[5]*v.z,z:A[6]*v.x+A[7]*v.y+A[8]*v.z});
export const rotationAxisAngle=(axis0:Vec3,theta:number):Mat3=>{const a=normalize(axis0),c=Math.cos(theta),s=Math.sin(theta),t=1-c;return [t*a.x*a.x+c,t*a.x*a.y-s*a.z,t*a.x*a.z+s*a.y,t*a.x*a.y+s*a.z,t*a.y*a.y+c,t*a.y*a.z-s*a.x,t*a.x*a.z-s*a.y,t*a.y*a.z+s*a.x,t*a.z*a.z+c]};
export const project=(v:Vec3,axis:Vec3)=>mul(axis,dot(v,axis));
export const reject=(v:Vec3,axis:Vec3)=>sub(v,project(v,axis));
export const mean=(xs:number[])=>xs.length?xs.reduce((a,b)=>a+b,0)/xs.length:0;
export const variance=(xs:number[])=>{if(xs.length<2)return 0;const m=mean(xs);return xs.reduce((s,x)=>s+(x-m)**2,0)/(xs.length-1)};
export const std=(xs:number[])=>Math.sqrt(variance(xs));
export const median=(xs:number[])=>{if(!xs.length)return 0;const a=[...xs].sort((x,y)=>x-y);const m=Math.floor(a.length/2);return a.length%2?a[m]:(a[m-1]+a[m])/2};
export const percentile=(xs:number[],p:number[])=>p.map(q=>{const a=[...xs].sort((x,y)=>x-y);if(!a.length)return 0;const i=(a.length-1)*q;const lo=Math.floor(i),hi=Math.ceil(i);return lo===hi?a[lo]:lerp(a[lo],a[hi],i-lo)});
export const sigmoid=(x:number)=>1/(1+Math.exp(-Math.max(-40,Math.min(40,x))));
export const softmax=(xs:number[])=>{const m=Math.max(...xs);const ex=xs.map(x=>Math.exp(x-m));const s=ex.reduce((a,b)=>a+b,0)||1;return ex.map(x=>x/s)};
export const logsumexp=(xs:number[])=>{const m=Math.max(...xs);return m+Math.log(xs.reduce((s,x)=>s+Math.exp(x-m),0)||1)};
